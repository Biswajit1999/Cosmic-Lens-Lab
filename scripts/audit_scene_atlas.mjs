#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const ALLOWED_COMPONENTS = new Set([
  'PointMass',
  'SubhaloPointMass',
  'SIS',
  'SoftenedIsothermalEllipse',
  'ExternalShear',
  'NFW',
]);
const ALLOWED_SOURCES = new Set(['Gaussian', 'SersicLight']);
const NON_HUMAN_AUTHORSHIP_PATTERNS = [/\[bot\]/i, /\bbot\b/i, /automated assistant/i, /language model/i, /co-authored-by/i, /generated by/i];

const checks = [];
const failures = [];
const warnings = [];

function repoPath(...parts) {
  return path.join(ROOT, ...parts);
}

function rel(filePath) {
  return path.relative(ROOT, filePath).replaceAll(path.sep, '/');
}

function finiteNumber(value) {
  return typeof value === 'number' && Number.isFinite(value);
}

function addCheck(name, passed, detail) {
  checks.push({ name, passed, detail });
  if (!passed) failures.push(`${name}: ${detail}`);
}

function addWarning(detail) {
  warnings.push(detail);
}

function sha256File(filePath) {
  const hash = crypto.createHash('sha256');
  hash.update(fs.readFileSync(filePath));
  return hash.digest('hex');
}

function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableJson(value[key])}`)
      .join(',')}}`;
  }
  return JSON.stringify(value);
}

function formatInteger(value) {
  return Number(value).toLocaleString('en-US');
}

function findJsonFiles(directory) {
  const out = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) out.push(...findJsonFiles(absolute));
    else if (entry.isFile() && entry.name.endsWith('.json')) out.push(absolute);
  }
  return out.sort((a, b) => rel(a).localeCompare(rel(b)));
}

function validateVec2(value, label, scenePath, sceneFailures) {
  if (!Array.isArray(value) || value.length !== 2 || !finiteNumber(value[0]) || !finiteNumber(value[1])) {
    sceneFailures.push(`${label} in ${scenePath} must be a finite [x, y] vector`);
    return false;
  }
  return true;
}

function validateComponent(component, scenePath, sceneFailures) {
  if (!component || typeof component !== 'object') {
    sceneFailures.push(`${scenePath} contains a non-object component`);
    return null;
  }
  if (!ALLOWED_COMPONENTS.has(component.type)) {
    sceneFailures.push(`${scenePath} has unsupported lens component ${component.type}`);
    return null;
  }

  if (component.center !== undefined) validateVec2(component.center, `${component.type}.center`, scenePath, sceneFailures);

  if (['PointMass', 'SubhaloPointMass', 'SIS'].includes(component.type)) {
    if (!finiteNumber(component.thetaE) || component.thetaE <= 0) {
      sceneFailures.push(`${scenePath} ${component.type}.thetaE must be positive`);
    }
  }
  if (component.type === 'SoftenedIsothermalEllipse') {
    if (!finiteNumber(component.thetaE) || component.thetaE <= 0) sceneFailures.push(`${scenePath} SIE thetaE must be positive`);
    if (!finiteNumber(component.q) || component.q <= 0 || component.q > 1) sceneFailures.push(`${scenePath} SIE q must be in (0, 1]`);
    if (!finiteNumber(component.core) || component.core < 0) sceneFailures.push(`${scenePath} SIE core must be non-negative`);
    if (!finiteNumber(component.phiDeg)) sceneFailures.push(`${scenePath} SIE phiDeg must be finite`);
  }
  if (component.type === 'ExternalShear') {
    if (!finiteNumber(component.gamma) || component.gamma < 0 || component.gamma >= 1) sceneFailures.push(`${scenePath} shear gamma must be in [0, 1)`);
    if (!finiteNumber(component.phiDeg)) sceneFailures.push(`${scenePath} shear phiDeg must be finite`);
  }
  if (component.type === 'NFW') {
    if (!finiteNumber(component.kappaS) || component.kappaS <= 0) sceneFailures.push(`${scenePath} NFW kappaS must be positive`);
    if (!finiteNumber(component.radiusScale) || component.radiusScale <= 0) sceneFailures.push(`${scenePath} NFW radiusScale must be positive`);
  }
  return component.type;
}

function validateScene(filePath) {
  const scenePath = rel(filePath);
  const text = fs.readFileSync(filePath, 'utf8');
  const sceneFailures = [];
  let scene;
  try {
    scene = JSON.parse(text);
  } catch (error) {
    sceneFailures.push(`${scenePath} is not valid JSON: ${error.message}`);
    return { path: scenePath, passed: false, failures: sceneFailures };
  }

  const authorshipPattern = NON_HUMAN_AUTHORSHIP_PATTERNS.find((pattern) => pattern.test(text));
  if (authorshipPattern) sceneFailures.push(`${scenePath} contains non-human authorship metadata pattern ${authorshipPattern}`);

  if (scene.version !== '1.0') sceneFailures.push(`${scenePath} version must be 1.0`);
  if (!scene.name || typeof scene.name !== 'string') sceneFailures.push(`${scenePath} needs a human-readable name`);
  if (!scene.cosmology || scene.cosmology.kind !== 'flatLCDM') sceneFailures.push(`${scenePath} must declare flatLCDM cosmology`);
  if (!finiteNumber(scene.cosmology?.H0) || scene.cosmology.H0 <= 0) sceneFailures.push(`${scenePath} H0 must be positive`);
  if (!finiteNumber(scene.cosmology?.Om0) || scene.cosmology.Om0 <= 0 || scene.cosmology.Om0 >= 1) sceneFailures.push(`${scenePath} Om0 must be in (0, 1)`);
  if (!Array.isArray(scene.planes) || scene.planes.length === 0) sceneFailures.push(`${scenePath} must include at least one lens plane`);
  if (!scene.source || !finiteNumber(scene.source.z)) sceneFailures.push(`${scenePath} must include finite source redshift`);
  if (!scene.source?.profile || !ALLOWED_SOURCES.has(scene.source.profile.type)) sceneFailures.push(`${scenePath} has unsupported source profile ${scene.source?.profile?.type}`);

  const componentCounts = {};
  let maxLensRedshift = -Infinity;
  let componentCount = 0;
  for (const [planeIndex, plane] of (scene.planes || []).entries()) {
    if (!finiteNumber(plane.z) || plane.z <= 0) sceneFailures.push(`${scenePath} plane ${planeIndex} z must be positive`);
    if (finiteNumber(plane.z)) maxLensRedshift = Math.max(maxLensRedshift, plane.z);
    if (!Array.isArray(plane.components) || plane.components.length === 0) {
      sceneFailures.push(`${scenePath} plane ${planeIndex} must contain components`);
      continue;
    }
    for (const component of plane.components) {
      const type = validateComponent(component, scenePath, sceneFailures);
      if (!type) continue;
      componentCounts[type] = (componentCounts[type] || 0) + 1;
      componentCount += 1;
    }
  }

  if (finiteNumber(scene.source?.z) && maxLensRedshift >= scene.source.z) {
    sceneFailures.push(`${scenePath} source redshift must be behind every lens plane`);
  }
  const profile = scene.source?.profile || {};
  if (profile.center !== undefined) validateVec2(profile.center, 'source.center', scenePath, sceneFailures);
  if (!finiteNumber(profile.radius) || profile.radius <= 0) sceneFailures.push(`${scenePath} source radius must be positive`);
  if (!finiteNumber(profile.flux) || profile.flux <= 0) sceneFailures.push(`${scenePath} source flux must be positive`);
  if (profile.axisRatio !== undefined && (!finiteNumber(profile.axisRatio) || profile.axisRatio <= 0 || profile.axisRatio > 1)) {
    sceneFailures.push(`${scenePath} source axisRatio must be in (0, 1]`);
  }
  if (profile.n !== undefined && (!finiteNumber(profile.n) || profile.n <= 0)) sceneFailures.push(`${scenePath} Sersic n must be positive`);

  if (!finiteNumber(scene.viewport?.halfWidthArcsec) || scene.viewport.halfWidthArcsec <= 0) sceneFailures.push(`${scenePath} viewport halfWidthArcsec must be positive`);
  if (!Number.isInteger(scene.viewport?.pixels) || scene.viewport.pixels < 64 || scene.viewport.pixels > 1024) {
    sceneFailures.push(`${scenePath} viewport pixels must be an integer from 64 to 1024`);
  }

  const isAnalyticRing = (scene.planes || []).length === 1
    && (scene.planes?.[0]?.components || []).length === 1
    && scene.planes[0].components[0].type === 'PointMass'
    && Array.isArray(scene.planes[0].components[0].center)
    && scene.planes[0].components[0].center[0] === 0
    && scene.planes[0].components[0].center[1] === 0
    && Array.isArray(profile.center)
    && profile.center[0] === 0
    && profile.center[1] === 0;

  return {
    path: scenePath,
    name: scene.name,
    passed: sceneFailures.length === 0,
    failures: sceneFailures,
    sha256: sha256File(filePath),
    category: scenePath.split('/')[1] || 'uncategorized',
    source_redshift: scene.source?.z,
    max_lens_redshift: maxLensRedshift,
    viewport_pixels: scene.viewport?.pixels,
    viewport_half_width_arcsec: scene.viewport?.halfWidthArcsec,
    component_count: componentCount,
    component_counts: componentCounts,
    analytic_reference: isAnalyticRing ? {
      kind: 'point-mass Einstein ring',
      thetaE_arcsec: scene.planes[0].components[0].thetaE,
    } : null,
  };
}

function buildMarkdown(payload) {
  const passCount = checks.filter((check) => check.passed).length;
  const lines = [];
  lines.push('# CosmicLens Scene Atlas');
  lines.push('');
  lines.push('This atlas is generated by `node scripts/audit_scene_atlas.mjs`. It validates every committed scene preset against the thin-lens JSON contract, component parameter ranges, source/lens redshift ordering, viewport limits and analytic-reference coverage.');
  lines.push('');
  lines.push(`- Status: **${payload.status.toUpperCase()}**`);
  lines.push(`- Integrity fingerprint: \`${payload.integrity_fingerprint}\``);
  lines.push(`- Scenes validated: ${formatInteger(payload.summary.scene_count)}`);
  lines.push(`- Checks passed: ${passCount}/${checks.length}`);
  lines.push(`- Warnings: ${warnings.length}`);
  lines.push('');
  lines.push('## Scene Inventory');
  lines.push('');
  lines.push('| Scene | Category | Components | Source z | Viewport | Hash |');
  lines.push('|---|---|---:|---:|---|---|');
  for (const scene of payload.scenes) {
    const components = Object.entries(scene.component_counts).map(([type, count]) => `${type} x${count}`).join(', ');
    lines.push(`| ${scene.name} | ${scene.category} | ${components || 'none'} | ${Number(scene.source_redshift).toFixed(3)} | ${scene.viewport_pixels}px / ${scene.viewport_half_width_arcsec}" | \`${scene.sha256}\` |`);
  }
  lines.push('');
  lines.push('## Component Coverage');
  lines.push('');
  lines.push('| Component | Count |');
  lines.push('|---|---:|');
  for (const [component, count] of Object.entries(payload.summary.component_counts)) {
    lines.push(`| ${component} | ${formatInteger(count)} |`);
  }
  lines.push('');
  lines.push('## Analytic Anchors');
  lines.push('');
  const anchors = payload.scenes.filter((scene) => scene.analytic_reference);
  if (anchors.length) {
    for (const scene of anchors) {
      lines.push(`- ${scene.name}: ${scene.analytic_reference.kind} with thetaE = ${scene.analytic_reference.thetaE_arcsec} arcsec.`);
    }
  } else {
    lines.push('- No analytic point-mass ring anchors found.');
  }
  lines.push('');
  lines.push('## Checks');
  lines.push('');
  lines.push('| Check | Result | Detail |');
  lines.push('|---|---|---|');
  for (const check of checks) {
    lines.push(`| ${check.name.replaceAll('|', '\\|')} | ${check.passed ? 'PASS' : 'FAIL'} | ${String(check.detail).replaceAll('|', '\\|')} |`);
  }
  if (warnings.length) {
    lines.push('');
    lines.push('## Warnings');
    lines.push('');
    for (const warning of warnings) lines.push(`- ${warning}`);
  }
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function writeIfChanged(relativePath, content) {
  const absolute = repoPath(relativePath);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  if (fs.existsSync(absolute) && fs.readFileSync(absolute, 'utf8') === content) return false;
  fs.writeFileSync(absolute, content, 'utf8');
  return true;
}

const sceneFiles = findJsonFiles(repoPath('examples'));
const scenes = sceneFiles.map(validateScene);
const failedScenes = scenes.filter((scene) => !scene.passed);
addCheck('scene files exist', scenes.length >= 6, `${formatInteger(scenes.length)} scenes`);
addCheck('all scenes pass JSON physics contract', failedScenes.length === 0, failedScenes.flatMap((scene) => scene.failures).slice(0, 10).join('; ') || 'all scenes pass');

const componentCounts = {};
for (const scene of scenes) {
  for (const [component, count] of Object.entries(scene.component_counts || {})) {
    componentCounts[component] = (componentCounts[component] || 0) + count;
  }
}
for (const component of ['PointMass', 'SIS', 'SoftenedIsothermalEllipse', 'ExternalShear', 'NFW']) {
  addCheck(`component coverage ${component}`, (componentCounts[component] || 0) > 0, `${componentCounts[component] || 0}`);
}
addCheck('analytic point-mass ring anchor', scenes.some((scene) => scene.analytic_reference?.kind === 'point-mass Einstein ring'), 'point-mass centered source benchmark');
addCheck('Python point-mass validation exists', fs.existsSync(repoPath('python/tests/test_point_mass.py')), 'python/tests/test_point_mass.py');
addCheck('Python SIS validation exists', fs.existsSync(repoPath('python/tests/test_sis.py')), 'python/tests/test_sis.py');
addCheck('TypeScript point-mass validation exists', fs.existsSync(repoPath('packages/physics-core/src/__tests__/pointMass.test.ts')), 'packages/physics-core/src/__tests__/pointMass.test.ts');
addCheck('TypeScript SIS validation exists', fs.existsSync(repoPath('packages/physics-core/src/__tests__/sis.test.ts')), 'packages/physics-core/src/__tests__/sis.test.ts');

const categories = [...new Set(scenes.map((scene) => scene.category))].sort();
if (!categories.includes('cosmography')) addWarning('No cosmography scene category found.');
if (!categories.includes('cluster')) addWarning('No cluster-scale scene category found.');

const fingerprint = crypto.createHash('sha256').update(stableJson({ checks, warnings, scenes })).digest('hex');
const payload = {
  format: 'cosmiclens-scene-atlas/v1',
  status: failures.length ? 'failed' : 'passed',
  integrity_fingerprint: fingerprint,
  summary: {
    scene_count: scenes.length,
    categories,
    component_counts: componentCounts,
  },
  scenes,
  checks,
  warnings,
};

writeIfChanged('docs/scene-atlas.json', `${JSON.stringify(payload, null, 2)}\n`);
writeIfChanged('SCENE_ATLAS.md', buildMarkdown(payload));

const passed = checks.filter((check) => check.passed).length;
console.log(`Scene atlas audit: ${passed}/${checks.length} checks passed, ${checks.length - passed} failed, ${warnings.length} warnings.`);
console.log(`Integrity fingerprint: ${fingerprint}`);
console.log('Wrote docs/scene-atlas.json and SCENE_ATLAS.md.');

if (failures.length) {
  console.error('\nFailures:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
